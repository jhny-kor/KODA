#!/usr/bin/env bash
# Packaging-side guard checks; does not contact Docker or a production host.
set -euo pipefail
here="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
bash -n "$here/apply.sh" "$here/rollback.sh"
grep -q 'sqlite3.connect(destination)' "$here/apply.sh"
grep -q 'pg_dumpall -U "\$POSTGRES_USER"' "$here/apply.sh"
grep -q 'service_refs=' "$here/apply.sh"
grep -q 'duplicate=0' "$here/apply.sh"
grep -q -- '--no-deps --force-recreate portal-web portal-api portal-worker' "$here/apply.sh"
grep -q -- '--no-deps gateway' "$here/apply.sh"
grep -q 'could not preserve current image' "$here/apply.sh"
grep -q 'compatibility contract is missing' "$here/apply.sh"
grep -q 'image-inventory.json' "$here/apply.sh"
grep -q 'portal-data-updater' "$here/apply.sh"
grep -q 'VULN_DATA_VOLUME_NAME' "$here/apply.sh"
grep -q 'configuration backup is incomplete' "$here/rollback.sh"
grep -q 'tracker-vuln-data-volume.tar.gz' "$here/apply.sh"
grep -q 'tar -czf - -C /data .' "$here/apply.sh"
grep -q '>"\$vuln_archive"' "$here/apply.sh"
! grep -q 'tar -czf /backup/tracker-vuln-data-volume.tar.gz' "$here/apply.sh"
grep -q 'migrate_legacy' "$here/apply.sh"
grep -q 'Tracker updater runtime ownership preparation failed' "$here/apply.sh"
grep -q 'gateway/.' "$here/rollback.sh"
grep -q 'compose.next.yaml' "$here/apply.sh"
grep -q 'could not preserve Tracker LDAP Compose networking' "$here/apply.sh"
grep -q '10.95.58.206' "$here/apply.sh"
grep -q '10.95.58.207' "$here/apply.sh"
grep -q 'TRACKER_DATA_UPDATE_KODA_GRYPE_BINARY' "$here/apply.sh"
grep -q -- '--network none' "$here/apply.sh"
grep -q 'legacy-current-target' "$here/rollback.sh"
grep -q 'compose stop portal-data-updater' "$here/rollback.sh"
echo "scheduled-release script guards passed"
